"""Run one online update, refresh rollout engines, then validate a second batch.

The second rollout is generated by the same live rollout manager after the
actor weight update, but is not sent through the optimizer. This is the
ordering required by the online MOPD closure canary.
"""

from __future__ import annotations

import json
import os
import sys
from datetime import UTC, datetime
from pathlib import Path

import ray
from slime.ray.placement_group import (
    create_placement_groups,
    create_rollout_manager,
    create_training_models,
)
from slime.utils.logging_utils import (
    configure_logger,
    finish_tracking,
    init_tracking,
    update_tracking_open_metrics,
)


def _env_flag(name: str, default: bool = False) -> bool:
    value = os.environ.get(name)
    if value is None:
        return default
    return value.strip().lower() in {"1", "true", "yes", "on"}


def _stamp_initial_weight_version(rollout_manager, version: str) -> None:
    """Record the checkpoint version without retransmitting identical weights.

    The rollout servers are launched from ``args.hf_checkpoint``.  When the
    actor is initialized from the matching torch-dist checkpoint, a first
    full NCCL broadcast is redundant and can leave CUDA autograd stream state
    alive before the first backward pass.  Version stamping preserves the
    concrete policy lineage required by the OpenReward evidence contract.
    """
    version = str(version).strip()
    if not version or version == "default":
        raise ValueError("initial policy weight version must be a concrete non-default value")
    engines, _lock, _num_new, _gpu_counts, _gpu_offsets = ray.get(
        rollout_manager.get_updatable_engines_and_lock.remote()
    )
    if not engines:
        raise RuntimeError("cannot stamp initial policy version: no updatable rollout engines")
    ray.get([engine.set_weight_version.remote(version) for engine in engines])
    print(
        "[online-transition] initial_policy_weight_version_set "
        f"version={version} engines={len(engines)}",
        flush=True,
    )


def train(args) -> None:
    start_rollout_id = int(args.start_rollout_id)
    validation_rollout_id = start_rollout_id + 1
    if int(args.num_rollout) != validation_rollout_id + 1:
        raise ValueError(
            "sync_validate requires exactly one training rollout followed by "
            "one validation rollout; set num_rollout=start_rollout_id+2"
        )
    if args.use_critic:
        raise ValueError("sync_validate is only supported for the actor-only MOPD canary")

    configure_logger()
    placement_groups = create_placement_groups(args)
    init_tracking(args)
    rollout_manager, _num_rollout_per_epoch = create_rollout_manager(
        args, placement_groups["rollout"]
    )
    router_addr = ray.get(rollout_manager.get_metrics_router_addr.remote())
    update_tracking_open_metrics(args, router_addr)
    actor_model, _critic_model = create_training_models(args, placement_groups, rollout_manager)

    if args.offload_rollout:
        ray.get(rollout_manager.onload_weights.remote())
    if _env_flag("SLIME_SYNC_VALIDATE_SKIP_INITIAL_WEIGHT_SYNC"):
        _stamp_initial_weight_version(
            rollout_manager,
            os.environ.get("SLIME_SYNC_VALIDATE_INITIAL_WEIGHT_VERSION", "0"),
        )
    else:
        actor_model.update_weights()
    if args.offload_rollout:
        ray.get(rollout_manager.onload_kv.remote())

    # Round one is the only optimizer input in this closure canary.
    first_data_ref = ray.get(rollout_manager.generate.remote(start_rollout_id))
    if args.offload_rollout:
        ray.get(rollout_manager.offload.remote())
    ray.get(actor_model.async_train(start_rollout_id, first_data_ref))
    actor_model.save_model(start_rollout_id, force_sync=True)
    if args.rollout_global_dataset:
        ray.get(rollout_manager.save.remote(start_rollout_id))
    if not args.offload_train:
        actor_model.clear_memory()
    if args.offload_rollout:
        ray.get(rollout_manager.onload_weights.remote())

    first_saved_at = datetime.now(UTC)
    print(
        "[online-transition] first_rollout_trained_and_saved "
        f"rollout_id={start_rollout_id}",
        flush=True,
    )
    actor_model.update_weights()
    refreshed_at = datetime.now(UTC)
    print(
        "[online-transition] policy_weights_refreshed_before_validation_rollout "
        f"rollout_id={validation_rollout_id}",
        flush=True,
    )
    if args.offload_rollout:
        ray.get(rollout_manager.onload_kv.remote())

    # Round two is deliberately generated only after update_weights returns.
    # The adapter logger writes the normal evidence receipt for this batch.
    validation_data_ref = ray.get(rollout_manager.generate.remote(validation_rollout_id))
    del validation_data_ref
    generated_at = datetime.now(UTC)
    print(
        "[online-transition] validation_rollout_generated_after_refresh "
        f"rollout_id={validation_rollout_id}",
        flush=True,
    )
    evidence_dir = Path(os.environ["SLIME_OPENREWARD_EVIDENCE_DIR"])
    transition = {
        "version": 1,
        "mode": "sync_validate",
        "first_rollout_id": start_rollout_id,
        "validation_rollout_id": validation_rollout_id,
        "first_rollout_trained_and_saved": True,
        "policy_weights_refreshed_before_validation_rollout": True,
        "validation_rollout_generated_after_refresh": True,
        "first_checkpoint_saved_at": first_saved_at.isoformat(),
        "weights_refreshed_at": refreshed_at.isoformat(),
        "validation_rollout_generated_at": generated_at.isoformat(),
    }
    evidence_dir.mkdir(parents=True, exist_ok=True)
    (evidence_dir / "transition.json").write_text(
        json.dumps(transition, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    ray.get(rollout_manager.dispose.remote())
    finish_tracking(args)


if __name__ == "__main__":
    try:
        from slime.utils.arguments import parse_args

        train(parse_args())
    except Exception:
        print("[online-transition] sync_validate driver failed", file=sys.stderr, flush=True)
        raise
